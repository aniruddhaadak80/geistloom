/**
 * routes.mjs — explorer route families.
 *
 * Generates static-param detail pages under apps/web/app/explorer/:
 *   hallmarks/[id]/page.tsx        (one per hallmark)
 *   interventions/[id]/page.tsx    (one per intervention)
 *   clocks/[id]/page.tsx           (one per epigenetic clock)
 *   scenarios/[id]/page.tsx        (one per future scenario)
 *
 * The id lists are extracted from the domain source of truth
 * (packages/core/src/domain/*.ts) at generation time, so the
 * routes can never drift from the data they render.
 *
 * Deterministic: mulberry32(4093) drives any ordering choices;
 * every run rewrites the same bytes.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { ENGINE_SEED, mulberry32, writeGenerated } from "./_shared.mjs";

/** Extract every `id: "..."` literal from a domain source file, in order. */
function extractIds(sourcePath) {
  const text = readFileSync(sourcePath, "utf8");
  const ids = [];
  const re = /\bid:\s*"([^"]+)"/g;
  let m = re.exec(text);
  while (m !== null) {
    ids.push(m[1]);
    m = re.exec(text);
  }
  if (ids.length === 0) {
    throw new Error(`no ids found in ${sourcePath}`);
  }
  return ids;
}

function listLiteral(ids) {
  const lines = ids.map((id) => `  "${id}",`);
  return `[\n${lines.join("\n")}\n] as const`;
}

