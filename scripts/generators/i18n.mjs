/**
 * Generate the locale tree into apps/web/i18n/.
 * @returns repo-relative paths of every file written.
 */
export function generateI18n() {
  const files = [];
  const localesDir = join(import.meta.dirname, "..", "..", "apps", "web", "i18n", "locales");

  for (const locale of LOCALES) {
    const { tree } = buildLocaleTree(locale);
    const json = `${JSON.stringify(tree, null, 2)}\n`;
    files.push(writeGenerated(join(localesDir, `${locale.code}.json`), json));
  }

  files.push(
    writeGenerated(
      join(import.meta.dirname, "..", "..", "apps", "web", "i18n", "locales-index.ts"),
      buildLocalesIndex(),
    ),
  );

  return files;
}
