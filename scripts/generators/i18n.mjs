  for (const locale of LOCALES) {
    lines.push(`import ${locale.code} from "./locales/${locale.code}.json";`);
  }
  lines.push("");
  lines.push("export const LOCALES = {");
  for (const locale of LOCALES) {
    lines.push(`  ${locale.code},`);
  }
  lines.push("} as const;");
  lines.push("");
  lines.push("export type LocaleCode = keyof typeof LOCALES;");
