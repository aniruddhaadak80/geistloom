/**
 * Load the real domain data. Runs under bun, which transpiles the
 * TypeScript domain modules on the fly — the single source of truth,
 * so generated defaults can never drift from packages/core.
 */
async function loadHallmarks() {
  const mod = await import(
    join(import.meta.dirname, "..", "..", "packages", "core", "src", "domain", "hallmarks.ts")
  );
  return mod.HALLMARKS;
}

function categoryTone(category) {
  switch (category) {
    case "primary":
      return "teal";
    case "antagonistic":
      return "amber";
    default:
      return "violet";
  }
}

