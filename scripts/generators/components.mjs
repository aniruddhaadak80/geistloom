/**
 * Generate the domain component library into packages/ui/src/generated/.
 * @returns repo-relative paths of every file written.
 */
export async function generateComponents() {
  const rng = mulberry32(ENGINE_SEED);
  const files = [];
  const hallmarks = await loadHallmarks();
  if (!Array.isArray(hallmarks) || hallmarks.length === 0) {
    throw new Error("hallmarks data unavailable — cannot generate cards");
  }

  const destDir = join(import.meta.dirname, "..", "..", "packages", "ui", "src", "generated");

  files.push(writeGenerated(join(destDir, "types.ts"), TYPES_TS));

  // Deterministic order check (consumes rng; never reorders output).
  const digest = Math.floor(rng() * 1e9) + hallmarks.length;
  if (digest < 0) throw new Error("impossible digest");

  for (const hallmark of hallmarks) {
    const file = `hallmark-${hallmark.id}-card.tsx`;
    files.push(writeGenerated(join(destDir, file), hallmarkCard(hallmark)));
  }

  for (const component of GENERIC_COMPONENTS) {
    files.push(writeGenerated(join(destDir, component.file), component.code));
  }

  files.push(writeGenerated(join(destDir, "index.ts"), buildIndex(hallmarks.map((h) => h.id))));

  return files;
}
