export function getIntervention(id: string): Intervention | undefined {
  return INTERVENTIONS.find((i) => i.id === id);
}

export function interventionsByEvidence(grade: EvidenceGrade): Intervention[] {
  return INTERVENTIONS.filter((i) => i.evidence === grade);
}

export function interventionsForHallmark(hallmarkId: string): Intervention[] {
  return INTERVENTIONS.filter((i) => i.targetHallmarkIds.includes(hallmarkId));
}

export function coverageAt(intervention: Intervention, year: number): number {
  if (year < intervention.adoptionYear) return 0;
  const t = (year - intervention.adoptionYear) * intervention.adoptionSpeed;
  // Logistic adoption, saturating at 0.92 (nothing reaches everyone).
  return 0.92 / (1 + Math.exp(-t));
}
