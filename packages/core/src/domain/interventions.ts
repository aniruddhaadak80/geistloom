/**
 * The Intervention Atlas.
 *
 * Every entry is a real or near-real intervention class with an evidence
 * grade, target hallmarks, and a quantified effect on the aging rate used by
 * the Century Engine. Evidence grades follow a simplified translatability
 * ladder: approved → clinical → preclinical → theoretical.
 */

export type EvidenceGrade = "approved" | "clinical" | "preclinical" | "theoretical";

export type InterventionClass =
  | "gene-therapy"
  | "gene-editing"
  | "small-molecule"
  | "biologic"
  | "cell-therapy"
  | "device"
  | "protocol";

export interface Intervention {
  readonly id: string;
  readonly name: string;
  readonly klass: InterventionClass;
  readonly evidence: EvidenceGrade;
  readonly targetHallmarkIds: readonly string[];
  /** Fraction of the natural aging rate removed at full coverage (0–0.9). */
  readonly agingRateReduction: number;
  /** Year the intervention becomes broadly adoptable in the simulation. */
  readonly adoptionYear: number;
  /** Adoption curve steepness (logistic). Higher = faster takeover. */
  readonly adoptionSpeed: number;
  /** Annual risk multiplier added at full coverage (safety tax, >1 = risky). */
  readonly riskMultiplier: number;
  readonly headline: string;
  readonly origin: string;
}

